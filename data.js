function costToLevel(type, level) {
  let se = 0,
    frag = 0;
  for (let i = 0; i < level; i++) {
    se += COST_TABLE[type][i][0];
    frag += COST_TABLE[type][i][1];
  }
  return { se, frag };
}
function costBetween(type, from, to) {
  const a = costToLevel(type, from),
    b = costToLevel(type, to);
  return { se: b.se - a.se, frag: b.frag - a.frag };
}
